"""Generate the illustrated app headers with ChatGPT (Codex CLI image generation) and wire them in.

    python islamhub/tools/gen_hero_art.py                 # every app that has no art yet
    python islamhub/tools/gen_hero_art.py waris zakat     # only these (regenerates)

Steps per app: Codex draws a 1536x1024 PNG into islamhub/assets/hero/raw/, Pillow crops and saves
islamhub/assets/hero/<app>.webp, and css/components/sakinah-hero-art.css is rewritten so every
app with art shows it in its header (the gold medallion is hidden there). Uses the ChatGPT plan
behind the local Codex app, not any paid image API.
"""
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "assets" / "hero" / "raw"
OUT = ROOT / "assets" / "hero"
CSS = ROOT / "css" / "components" / "sakinah-hero-art.css"
MODEL = "gpt-5.6-terra"

STYLE = (
    "Style: calm, premium editorial illustration for a Muslim lifestyle app. Flat vector shapes with soft paper grain "
    "and gentle gradients, rounded forms, subtle Islamic geometric line patterns. Strict palette: deep green #1f3d33, "
    "sage green #2f6b55, soft mint #dfe9e2, warm cream #f6efd9, muted gold #b08a3e, light gold #e0c27f, a touch of "
    "terracotta #c07a4a. The background is deep green #1f3d33 on the left fading to the scene on the right. Wide "
    "landscape 1536x1024; main subject in the RIGHT half, the LEFT half kept as calm dark green space for text. "
    "No text, no letters, no Arabic script, no numbers, no logos, no watermark. No people, no faces, no animals."
)

# header class -> subject
APPS = {
    "alquran": "an open mushaf on a carved wooden rehal stand, pages drawn only as soft abstract lines, a small brass lamp glowing beside it",
    "zakat": "a woven basket of rice grains and dates beside a small stack of gold coins and a cloth pouch, warm light",
    "hadits": "a stack of classical bound books with leather spines and ribbon bookmarks on a low wooden desk, a reed pen and inkwell",
    "kalender": "a crescent moon and its phases arching over soft desert hills at dusk, a few stars",
    "qibla": "an ornate brass compass with geometric engravings resting on a prayer mat corner",
    "waris": "a balanced brass scale with geometric engravings next to rolled parchment scrolls and a small house silhouette",
    "sholat": "a folded prayer rug in an arched mosque niche (mihrab) with soft light through a lattice window",
    "asmaul": "a large eight-pointed golden geometric rosette glowing softly, layered star patterns",
    "dzikir": "a string of wooden prayer beads (misbaha) coiled on cream linen with a sprig of olive leaves",
    "fiqh": "a brass ablution jug (ibrik) and basin beside a closed book and a folded prayer rug",
    "haji": "the Kaaba draped in black cloth with a gold band, simplified and seen from a distance, arches of the Grand Mosque around it",
    "sirah": "a quiet desert oasis with date palms and a distant city of domes and minarets at golden hour",
    "streaming": "a vintage wooden radio and a small screen showing a mosque silhouette, gentle sound waves",
}


def codex():
    found = sorted(Path.home().glob("AppData/Local/OpenAI/Codex/bin/*/codex.exe"), key=lambda p: p.stat().st_mtime)
    if not found:
        sys.exit("Codex CLI not found (install the Codex desktop app).")
    return str(found[-1])


def generate(app, subject):
    RAW.mkdir(parents=True, exist_ok=True)
    target = RAW / f"{app}.png"
    prompt = (f"Use your built-in image generation tool to create ONE image and save it as PNG at exactly this path: "
              f"{target.name} (relative to the current working directory). Do not create any other files. "
              f"If the image tool fails, print its error verbatim.\n\nSubject: {subject}.\n{STYLE}")
    r = subprocess.run([codex(), "exec", "-m", MODEL, "--skip-git-repo-check", "--sandbox", "workspace-write",
                        "-C", str(RAW), "-"], input=prompt, text=True, capture_output=True, encoding="utf-8")
    if not target.exists():
        tail = (r.stdout + r.stderr).strip().splitlines()[-3:]
        print(f"  {app}: no image ({' / '.join(tail)})")
        return False
    img = Image.open(target).convert("RGB")
    w, h = img.size
    # keep the right-hand scene, banner ratio 3:2
    img = img.crop((0, 0, w, min(h, int(w / 1.5)))).resize((1200, 800), Image.LANCZOS)
    img.save(OUT / f"{app}.webp", "WEBP", quality=82, method=6)
    print(f"  {app}: {(OUT / f'{app}.webp').stat().st_size // 1024} KB")
    return True


def write_css():
    rules = ["/* GENERATED by tools/gen_hero_art.py. Header illustrations; edit the script, not this file. */"]
    for app in APPS:
        if (OUT / f"{app}.webp").exists():
            sel = f'html[data-theme="sakinah"] .{app}-header'
            rules.append(f'{sel} {{ --hero-art: url("../../assets/hero/{app}.webp"); padding-right: 42% !important; min-height: 164px; }}')
            rules.append(f"{sel} :is(h1, h2) > :is(i, svg) {{ display: none !important; }}")
    CSS.write_text("\n".join(rules) + "\n", encoding="utf-8")
    print(f"wrote {CSS.relative_to(ROOT)} ({len(rules) // 2} apps with art)")


def main(only):
    todo = only or [a for a in APPS if not (OUT / f"{a}.webp").exists()]
    for app in todo:
        print(f"generating {app} ...")
        generate(app, APPS[app])
    write_css()
    shutil.rmtree(RAW, ignore_errors=True)


if __name__ == "__main__":
    main(sys.argv[1:])
