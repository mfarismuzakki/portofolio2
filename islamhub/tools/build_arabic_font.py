"""Write css/components/sakinah-arabic.css: every Arabic text outside the Qur'an reader uses the
Mushaf Standar Indonesia face (LPMQ Isep Misbah), like the reader does.

    python islamhub/tools/build_arabic_font.py

Collects every selector whose font-family names an Arabic face (Amiri, Scheherazade, Noto Naskh,
Uthmanic...) in the component CSS. The Qur'an reader is left out: there the user picks the font.
"""
import re
from pathlib import Path

import tinycss2

ROOT = Path(__file__).resolve().parent.parent / "css" / "components"
OUT = ROOT / "sakinah-arabic.css"
SKIP = {"alquran.css", "sakinah-quran.css", "sakinah-theme.css", "sakinah-arabic.css"}
ARABIC_FACE = re.compile(r"amiri|scheherazade|naskh|uthman|kfgqpc|lateef|arabic|lpmq", re.I)
# Qur'an reader classes keep the user's font choice.
READER = re.compile(r"verse-arabic|basmalah-arabic|\.arabic-text|mushaf|surah-arabic-name|\.(uthmanic|amiri|scheherazade|naskh|kufi|noto-naskh|lpmq)\b")
THEME_PREFIX = re.compile(r'^html\[data-theme(="[a-z]+")?\]\s*')
# decorative watermarks or Latin-only text that happen to name an Arabic face
DECORATIVE = {".home-hero::before", ".kalender-hijri-date"}
# short inline labels inside cards keep their own line height
INLINE = {".arabic-name", ".alaihissalam", ".orbit-card-glyph", ".prophet-arabic-title", ".person-arabic", ".kons-core-arabic",
          ".adm-center-next-arabic", ".adm-prayer-arabic", ".gk-arabic"}

TEMPLATE = """/* GENERATED by tools/build_arabic_font.py. Do not edit. */
/* Arabic text across the app (du'a, hadith, Asmaul Husna, dalil...) in the Mushaf Standar
   Indonesia face, matching the Qur'an reader. 'IH Arabic' covers Arabic code points only, so
   Latin text in the same element keeps the UI font. */
@font-face {
  font-family: 'IH Arabic';
  src: url('../../vendor/fonts/lpmq-isep-misbah.woff2') format('woff2');
  font-display: swap;
  unicode-range: U+0600-06FF, U+0750-077F, U+08A0-08FF, U+FB50-FDFF, U+FE70-FEFF;
}
ALL {
  font-family: 'IH Arabic', 'Plus Jakarta Sans', 'Amiri', sans-serif !important;
  letter-spacing: 0 !important;
}
BLOCK {
  line-height: 2.05 !important;
  overflow: visible !important;
  padding-top: .15em;
}
"""


def selectors():
    found = []
    for css in sorted(ROOT.glob("*.css")):
        if css.name in SKIP:
            continue
        rules = tinycss2.parse_stylesheet(css.read_text(encoding="utf-8"), skip_comments=True, skip_whitespace=True)
        stack = list(rules)
        while stack:
            r = stack.pop(0)
            if r.type == "at-rule" and r.content is not None and r.lower_at_keyword == "media":
                stack[0:0] = tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True)
                continue
            if r.type != "qualified-rule":
                continue
            fam = re.search(r"font-family\s*:\s*([^;]+)", tinycss2.serialize(r.content))
            if not fam or not ARABIC_FACE.search(fam.group(1)):
                continue
            for sel in tinycss2.serialize(r.prelude).split(","):
                sel = THEME_PREFIX.sub("", " ".join(sel.split()))
                if sel and sel not in DECORATIVE and not READER.search(sel) and sel not in found:
                    found.append(sel)
    return found


def main():
    sels = selectors()
    block = [x for x in sels if x not in INLINE]
    join = lambda xs: ",\n".join(f"html[data-theme] {x}" for x in xs)
    OUT.write_text(TEMPLATE.replace("ALL", join(sels)).replace("BLOCK", join(block)), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(sels)} selectors ({len(block)} blocks)")


if __name__ == "__main__":
    main()
